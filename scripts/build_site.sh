#!/usr/bin/env bash
# Wrap artifact.html (the page fragment published as a Claude artifact) into a
# complete index.html that GitHub Pages can serve. Run from anywhere.
set -euo pipefail
cd "$(dirname "$0")/.."
{
  cat <<'HEAD'
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>Powder Ledger</title>
<meta name="description" content="This winter's snowfall at seven Rocky Mountain resorts, set against each of the last ten seasons.">
<meta property="og:title" content="Powder Ledger">
<meta property="og:description" content="This winter's snowfall at seven Rocky Mountain resorts, set against each of the last ten seasons.">
<meta property="og:type" content="website">
<style>:root{box-sizing:border-box;padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
</head>
<body>
<!-- Generated by scripts/build_site.sh from artifact.html. Edit artifact.html, not this file. -->
HEAD
  cat artifact.html
  printf '</body>\n</html>\n'
} > index.html
echo "built index.html ($(wc -c < index.html) bytes)"
